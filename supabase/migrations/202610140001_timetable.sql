create table if not exists public.timetable_entries (
  id bigint generated by default as identity primary key,
  day_of_week smallint not null check (day_of_week between 1 and 5),
  start_time time not null,
  end_time time not null,
  course_code text not null,
  course_title text not null,
  venue text not null,
  lecturer text,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint timetable_entry_time_order check (end_time > start_time),
  constraint timetable_entry_unique unique (day_of_week, start_time, course_code)
);

create table if not exists public.timetable_changes (
  id bigint generated by default as identity primary key,
  change_date date not null,
  moved_to_date date,
  entry_id bigint references public.timetable_entries(id) on delete cascade,
  change_type text not null check (
    change_type in ('cancelled', 'moved', 'venue_changed', 'added')
  ),
  new_start_time time,
  new_end_time time,
  new_venue text,
  course_code text,
  course_title text,
  note text,
  created_by text not null,
  created_at timestamptz not null default now(),
  constraint timetable_change_shape check (
    (change_type = 'added' and entry_id is null and new_start_time is not null and new_end_time is not null and new_venue is not null and course_code is not null and course_title is not null)
    or
    (change_type = 'cancelled' and entry_id is not null)
    or
    (change_type = 'venue_changed' and entry_id is not null and new_venue is not null)
    or
    (change_type = 'moved' and entry_id is not null and moved_to_date is not null and new_start_time is not null and new_end_time is not null)
  ),
  constraint timetable_change_time_order check (
    new_start_time is null or new_end_time is null or new_end_time > new_start_time
  )
);

create table if not exists public.timetable_settings (
  id boolean primary key default true check (id),
  auto_send_enabled boolean not null default false,
  evening_enabled boolean not null default true,
  morning_enabled boolean not null default true,
  class_now_enabled boolean not null default true,
  class_now_lead_minutes smallint not null default 10 check (class_now_lead_minutes between 0 and 60),
  evening_time time not null default '19:00',
  morning_time time not null default '06:00',
  target_group_id text not null default '',
  target_group_name text not null default '',
  skip_dates date[] not null default '{}',
  grace_minutes smallint not null default 10 check (grace_minutes between 1 and 30),
  updated_at timestamptz not null default now()
);

create table if not exists public.timetable_send_log (
  id bigint generated by default as identity primary key,
  kind text not null check (kind in ('evening', 'morning', 'class_now')),
  for_date date not null,
  slot_key text not null,
  status text not null check (status in ('pending', 'sent', 'failed', 'skipped')),
  message_text text not null,
  error text,
  sent_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint timetable_send_once unique (kind, for_date, slot_key)
);

